// Command clientgen generates the vm-agent Go client (pkg/client) from
// docs/openapi.yaml. It supports the OpenAPI subset the spec uses: object
// schemas with properties, required, nullable, allOf-wrapped references,
// arrays, string-keyed maps, and operations whose 200 response is the JSON
// envelope (allOf Envelope + result), a raw binary body, or both (with the
// x-stream-request extension naming the request field that selects the
// stream).
//
//	cd tools && go run ./clientgen -spec ../docs/openapi.yaml -out ../pkg/client/client_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
	"unicode"

	"gopkg.in/yaml.v3"
)

func main() {
	specPath := flag.String("spec", "../docs/openapi.yaml", "OpenAPI document")
	out := flag.String("out", "../pkg/client/client_gen.go", "output file")
	pkg := flag.String("pkg", "client", "package name")
	flag.Parse()
	src, err := os.ReadFile(*specPath)
	if err != nil {
		log.Fatal(err)
	}
	code, err := Generate(src, *pkg)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		log.Fatal(err)
	}
}

// skipped schemas are handled by the hand-written runtime.
var skipped = map[string]bool{"Envelope": true, "ErrorResponse": true, "Error": true}

// node helpers over yaml.Node mappings, which preserve document order.

func get(n *yaml.Node, key string) *yaml.Node {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

func pairs(n *yaml.Node) [][2]*yaml.Node {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	var out [][2]*yaml.Node
	for i := 0; i+1 < len(n.Content); i += 2 {
		out = append(out, [2]*yaml.Node{n.Content[i], n.Content[i+1]})
	}
	return out
}

func items(n *yaml.Node) []*yaml.Node {
	if n == nil {
		return nil
	}
	return n.Content
}

func str(n *yaml.Node, key string) string {
	if v := get(n, key); v != nil {
		return v.Value
	}
	return ""
}

func boolean(n *yaml.Node, key string) bool { return str(n, key) == "true" }

type generator struct {
	root    *yaml.Node
	buf     bytes.Buffer
	extra   bytes.Buffer // merged oneOf structs, emitted after the operations
	imports map[string]bool
	merged  map[string]bool
	current string // Go name of the operation being generated
}

func (g *generator) p(format string, args ...any) { fmt.Fprintf(&g.buf, format, args...) }

// Generate renders the client source.
func Generate(src []byte, pkg string) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(src, &doc); err != nil {
		return nil, err
	}
	g := &generator{root: doc.Content[0], imports: map[string]bool{"context": true}}
	var body bytes.Buffer
	g.buf = body
	if err := g.schemas(); err != nil {
		return nil, err
	}
	if err := g.operations(); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by tools/clientgen from docs/openapi.yaml. DO NOT EDIT.\n\npackage %s\n\nimport (\n", pkg)
	imports := make([]string, 0, len(g.imports))
	for imp := range g.imports {
		imports = append(imports, imp)
	}
	sort.Strings(imports)
	for _, imp := range imports {
		fmt.Fprintf(&out, "\t%q\n", imp)
	}
	out.WriteString(")\n\n")
	out.Write(g.buf.Bytes())
	out.Write(g.extra.Bytes())
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("format generated code: %w", err)
	}
	return formatted, nil
}

func refName(ref string) string { return ref[strings.LastIndex(ref, "/")+1:] }

// goName converts snake_case, kebab-case or camelCase to an exported Go name.
func goName(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == '.' || r == '/' || r == ' ' })
	var b strings.Builder
	for _, part := range parts {
		upper := strings.ToUpper(part)
		switch upper {
		case "ID", "URL", "PID", "MS", "UAC", "DPI", "API", "SHA256", "JSON", "UTF8", "HTTP", "DX", "DY":
			b.WriteString(upper)
			continue
		}
		r := []rune(part)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

func comment(text, indent string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	var b strings.Builder
	for _, line := range strings.Split(text, "\n") {
		b.WriteString(indent + "// " + strings.TrimRight(line, " ") + "\n")
	}
	return b.String()
}

// unwrap resolves allOf: [ {$ref} ] to the referenced schema node.
func unwrap(s *yaml.Node) *yaml.Node {
	if all := get(s, "allOf"); all != nil && len(all.Content) == 1 && get(all.Content[0], "$ref") != nil {
		return all.Content[0]
	}
	return s
}

// goType maps a schema to a Go type. optional selects pointer forms for
// scalars and structs.
func (g *generator) goType(s *yaml.Node, optional bool) (string, error) {
	nullable := boolean(s, "nullable")
	s = unwrap(s)
	ptr := func(t string) string {
		if optional || nullable {
			return "*" + t
		}
		return t
	}
	if ref := str(s, "$ref"); ref != "" {
		return ptr(refName(ref)), nil
	}
	switch str(s, "type") {
	case "string":
		switch str(s, "format") {
		case "date-time":
			g.imports["time"] = true
			return ptr("time.Time"), nil
		case "byte":
			return "[]byte", nil
		case "binary":
			return "", fmt.Errorf("binary schemas are only valid as stream bodies")
		}
		return ptr("string"), nil
	case "integer":
		if str(s, "format") == "int64" {
			return ptr("int64"), nil
		}
		return ptr("int"), nil
	case "number":
		return ptr("float64"), nil
	case "boolean":
		return ptr("bool"), nil
	case "array":
		item, err := g.goType(get(s, "items"), false)
		if err != nil {
			return "", err
		}
		return "[]" + item, nil
	case "object":
		if ap := get(s, "additionalProperties"); ap != nil {
			if ap.Kind == yaml.ScalarNode {
				return "map[string]any", nil
			}
			v, err := g.goType(ap, false)
			if err != nil {
				return "", err
			}
			return "map[string]" + v, nil
		}
		if get(s, "properties") == nil {
			return "map[string]any", nil
		}
	}
	return "", fmt.Errorf("unsupported schema at line %d", s.Line)
}

func (g *generator) schemas() error {
	schemas := get(get(g.root, "components"), "schemas")
	for _, kv := range pairs(schemas) {
		name, s := kv[0].Value, kv[1]
		if skipped[name] {
			continue
		}
		g.p("%s", comment(fmt.Sprintf("%s is the %s schema.\n%s", name, name, str(s, "description")), ""))
		props := get(s, "properties")
		if props == nil {
			g.p("type %s struct{}\n\n", name)
			continue
		}
		required := map[string]bool{}
		for _, r := range items(get(s, "required")) {
			required[r.Value] = true
		}
		g.p("type %s struct {\n", name)
		for _, p := range pairs(props) {
			field, ps := p[0].Value, p[1]
			req := required[field]
			t, err := g.goType(ps, !req)
			if err != nil {
				return fmt.Errorf("%s.%s: %w", name, field, err)
			}
			desc := str(ps, "description")
			if desc == "" {
				desc = str(unwrap(ps), "description")
			}
			if enum := get(ps, "enum"); enum != nil {
				var vals []string
				for _, v := range items(enum) {
					vals = append(vals, v.Value)
				}
				desc = strings.TrimSpace(desc + " One of: " + strings.Join(vals, ", ") + ".")
			}
			if def := str(ps, "default"); def != "" {
				desc = strings.TrimSpace(desc + " Default " + def + ".")
			}
			tag := field
			if !req {
				tag += ",omitempty"
			}
			g.p("%s", comment(desc, "\t"))
			g.p("\t%s %s `json:%q`\n", goName(field), t, tag)
		}
		g.p("}\n\n")
	}
	return nil
}

type operation struct {
	method, path, id string
	node             *yaml.Node
}

func (g *generator) resolveResponse(n *yaml.Node) *yaml.Node {
	if ref := str(n, "$ref"); ref != "" {
		return get(get(get(g.root, "components"), "responses"), refName(ref))
	}
	return n
}

// oneOfName registers a struct merging the object variants of a oneOf
// result (e.g. exec's synchronous and detached results) and returns its
// name; every field becomes optional because only one variant is present.
func (g *generator) oneOfName(name string, variants *yaml.Node) (string, error) {
	if g.merged == nil {
		g.merged = map[string]bool{}
	}
	if g.merged[name] {
		return name, nil
	}
	g.merged[name] = true
	var doc []string
	fields := map[string]bool{}
	var b strings.Builder
	fmt.Fprintf(&b, "type %s struct {\n", name)
	schemas := get(get(g.root, "components"), "schemas")
	for _, v := range items(variants) {
		ref := str(v, "$ref")
		if ref == "" {
			return "", fmt.Errorf("oneOf variants must be references")
		}
		doc = append(doc, refName(ref))
		for _, p := range pairs(get(get(schemas, refName(ref)), "properties")) {
			field := p[0].Value
			if fields[field] {
				continue
			}
			fields[field] = true
			t, err := g.goType(p[1], true)
			if err != nil {
				return "", err
			}
			if desc := str(p[1], "description"); desc != "" {
				b.WriteString(comment(desc, "\t"))
			}
			fmt.Fprintf(&b, "\t%s %s `json:\"%s,omitempty\"`\n", goName(field), t, field)
		}
	}
	b.WriteString("}\n\n")
	g.extra.WriteString(comment(fmt.Sprintf("%s holds whichever of %s the response carries.", name, strings.Join(doc, " or ")), ""))
	g.extra.WriteString(b.String())
	return name, nil
}

// resultType extracts the result schema from an envelope allOf.
func (g *generator) resultType(schema *yaml.Node) (string, error) {
	all := get(schema, "allOf")
	if all == nil || len(all.Content) != 2 {
		return "", fmt.Errorf("JSON response must be allOf [Envelope, {result}] (line %d)", schema.Line)
	}
	result := get(get(all.Content[1], "properties"), "result")
	if result == nil {
		return "", fmt.Errorf("envelope lacks result (line %d)", schema.Line)
	}
	if variants := get(result, "oneOf"); variants != nil {
		return g.oneOfName(g.current+"Response", variants)
	}
	return g.goType(result, false)
}

func (g *generator) operations() error {
	var ops []operation
	for _, kv := range pairs(get(g.root, "paths")) {
		for _, m := range pairs(kv[1]) {
			ops = append(ops, operation{method: strings.ToUpper(m[0].Value), path: kv[0].Value, id: str(m[1], "operationId"), node: m[1]})
		}
	}
	g.p("// Operation identifies one API endpoint.\ntype Operation struct {\n\tID     string\n\tMethod string\n\tPath   string\n}\n\n")
	g.p("// Operations lists every endpoint of docs/openapi.yaml.\nvar Operations = []Operation{\n")
	for _, op := range ops {
		g.p("\t{ID: %q, Method: %q, Path: %q},\n", op.id, op.method, op.path)
	}
	g.p("}\n\n")
	for _, op := range ops {
		if err := g.operation(op); err != nil {
			return fmt.Errorf("%s %s: %w", op.method, op.path, err)
		}
	}
	return nil
}

type param struct {
	name, in, goName, goType string
	schema                   *yaml.Node
}

func (g *generator) operation(op operation) error {
	if op.id == "" {
		return fmt.Errorf("missing operationId")
	}
	name := goName(op.id)
	g.current = name
	var pathParams, queryParams []param
	for _, pn := range items(get(op.node, "parameters")) {
		if ref := str(pn, "$ref"); ref != "" {
			pn = get(get(get(g.root, "components"), "parameters"), refName(ref))
		}
		p := param{name: str(pn, "name"), in: str(pn, "in"), schema: get(pn, "schema")}
		p.goName = goName(p.name)
		switch p.in {
		case "header":
			continue // X-Request-Id and X-Timeout-Ms are call options
		case "path":
			t, err := g.goType(p.schema, false)
			if err != nil {
				return err
			}
			p.goType = t
			pathParams = append(pathParams, p)
		case "query":
			t, err := g.goType(p.schema, true)
			if err != nil {
				return err
			}
			p.goType = t
			queryParams = append(queryParams, p)
		}
	}
	// Request body.
	bodyType, multipart := "", false
	if rb := get(op.node, "requestBody"); rb != nil {
		content := get(rb, "content")
		if js := get(content, "application/json"); js != nil {
			t, err := g.goType(get(js, "schema"), false)
			if err != nil {
				return err
			}
			bodyType = t
		} else if get(content, "multipart/form-data") != nil {
			multipart = true
		}
	}
	// Response.
	resp := g.resolveResponse(get(get(op.node, "responses"), "200"))
	content := get(resp, "content")
	resultType, stream := "", false
	for _, ct := range pairs(content) {
		if ct[0].Value == "application/json" {
			t, err := g.resultType(get(ct[1], "schema"))
			if err != nil {
				return err
			}
			resultType = t
		} else {
			stream = true
		}
	}
	// Parameters struct for query parameters.
	paramsType := ""
	if len(queryParams) > 0 {
		paramsType = name + "Params"
		g.p("// %s holds the query parameters of %s.\ntype %s struct {\n", paramsType, name, paramsType)
		for _, q := range queryParams {
			g.p("\t%s %s\n", q.goName, q.goType)
		}
		g.p("}\n\n")
	}
	args := "ctx context.Context"
	for _, p := range pathParams {
		args += fmt.Sprintf(", %s %s", lowerFirst(p.goName), p.goType)
	}
	if paramsType != "" {
		args += ", params *" + paramsType
	}
	if bodyType != "" {
		args += ", body *" + bodyType
	}
	if multipart {
		args += ", files []UploadFile, options *UploadOptions"
	}
	args += ", opts ...Option"

	pathExpr := fmt.Sprintf("%q", op.path)
	if len(pathParams) > 0 {
		g.imports["net/url"] = true
		pathExpr = fmt.Sprintf("%q", op.path)
		for _, p := range pathParams {
			pathExpr = fmt.Sprintf("strings.ReplaceAll(%s, %q, url.PathEscape(%s))", pathExpr, "{"+p.name+"}", lowerFirst(p.goName))
		}
		g.imports["strings"] = true
	}
	queryExpr := "nil"
	if paramsType != "" {
		g.imports["net/url"] = true
		queryExpr = "q"
	}
	bodyExpr := "nil"
	if bodyType != "" {
		bodyExpr = "body"
	}
	summary := str(op.node, "summary")
	desc := str(op.node, "description")
	doc := fmt.Sprintf("%s calls %s %s: %s.", name, op.method, op.path, strings.TrimSuffix(summary, "."))
	if desc != "" {
		doc += "\n\n" + desc
	}
	writeQuery := func() {
		if paramsType == "" {
			return
		}
		g.p("\tq := url.Values{}\n\tif params != nil {\n")
		for _, qp := range queryParams {
			g.p("\t\tif params.%s != nil {\n\t\t\tq.Set(%q, fmt.Sprint(*params.%s))\n\t\t}\n", qp.goName, qp.name, qp.goName)
			g.imports["fmt"] = true
		}
		g.p("\t}\n")
	}
	switch {
	case multipart:
		g.p("%s", comment(doc, ""))
		g.p("func (c *Client) %s(%s) (*%s, error) {\n", name, args, strings.TrimPrefix(resultType, "*"))
		g.p("\tvar out %s\n\tif err := c.doMultipart(ctx, %q, %s, files, options, &out, opts); err != nil {\n\t\treturn nil, err\n\t}\n\treturn &out, nil\n}\n\n", strings.TrimPrefix(resultType, "*"), op.method, pathExpr)
	case resultType != "":
		g.p("%s", comment(doc, ""))
		if resultType == "Empty" {
			g.p("func (c *Client) %s(%s) error {\n", name, args)
			writeQuery()
			g.p("\treturn c.do(ctx, %q, %s, %s, %s, nil, opts)\n}\n\n", op.method, pathExpr, queryExpr, bodyExpr)
		} else {
			g.p("func (c *Client) %s(%s) (*%s, error) {\n", name, args, resultType)
			writeQuery()
			g.p("\tvar out %s\n\tif err := c.do(ctx, %q, %s, %s, %s, &out, opts); err != nil {\n\t\treturn nil, err\n\t}\n\treturn &out, nil\n}\n\n", resultType, op.method, pathExpr, queryExpr, bodyExpr)
		}
		if stream {
			ext := get(op.node, "x-stream-request")
			if ext == nil || bodyType == "" {
				return fmt.Errorf("JSON and binary responses need x-stream-request")
			}
			field, value := goName(str(ext, "field")), str(ext, "value")
			g.p("// %sStream is %s with %s=%s: the raw body and its metadata headers.\n", name, name, str(ext, "field"), value)
			g.p("func (c *Client) %sStream(%s) (*StreamResponse, error) {\n", name, args)
			g.p("\tb := %s{}\n\tif body != nil {\n\t\tb = *body\n\t}\n\tv := %q\n\tb.%s = &v\n", bodyType, value, field)
			g.p("\treturn c.doStream(ctx, %q, %s, %s, &b, opts)\n}\n\n", op.method, pathExpr, queryExpr)
		}
	case stream:
		g.p("%s", comment(doc, ""))
		g.p("func (c *Client) %s(%s) (*StreamResponse, error) {\n", name, args)
		writeQuery()
		g.p("\treturn c.doStream(ctx, %q, %s, %s, %s, opts)\n}\n\n", op.method, pathExpr, queryExpr, bodyExpr)
	default:
		return fmt.Errorf("no usable 200 response")
	}
	return nil
}

func lowerFirst(s string) string {
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	out := string(r)
	if strings.HasSuffix(out, "ID") && len(out) > 2 {
		return out
	}
	return out
}
